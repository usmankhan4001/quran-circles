const pascal = (slug) =>
  slug
    .split('-')
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');

function weightBlock(src, weight) {
  const start = src.indexOf(`'${weight}',`);
  if (start < 0) throw new Error(`no ${weight}`);
  const next = src.indexOf("\n  [\n    '", start);
  return src.slice(start, next < 0 ? src.length : next);
}

const paths = (block) =>
  [...block.matchAll(/<Path\s+([^>]*?)\/>/g)].map((m) => ({
    d: /d="([^"]+)"/.exec(m[1])[1],
    back: /opacity=\{duotoneOpacity\}/.test(m[1]),
  }));

const out = {};
for (const slug of slugs) {
  const src = readFileSync(join(pkgDir, 'src', 'defs', `${pascal(slug)}.tsx`), 'utf8');
  const duo = paths(weightBlock(src, 'duotone'));
  out[slug] = {
    regular: paths(weightBlock(src, 'regular')).map((p) => p.d),
    bold: paths(weightBlock(src, 'bold')).map((p) => p.d),
    fill: paths(weightBlock(src, 'fill')).map((p) => p.d),
    duotone: duo.filter((p) => p.back).map((p) => p.d),
    duotoneFront: duo.filter((p) => !p.back).map((p) => p.d),
  };
}

