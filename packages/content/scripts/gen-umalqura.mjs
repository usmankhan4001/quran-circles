/* global console, URL */
// Regenerates src/prayer/umalqura-data.ts from the @umalqura/core calendar (MIT licence,
// https://github.com/umalqura/umalqura). Run with TZ=UTC so the library's local dates are
// the calendar days:  TZ=UTC node scripts/gen-umalqura.mjs
import umalqura from '@umalqura/core';
import { writeFileSync } from 'node:fs';

if (new Date(2026, 0, 1).getTimezoneOffset() !== 0) {
  throw new Error('Run with TZ=UTC');
}
const lib = umalqura.default ?? umalqura;
const DAY = 86_400_000;
const first = Date.UTC(1900, 3, 30);
const last = Date.UTC(2077, 10, 16);

const years = new Map();
for (let t = first; t <= last; t += DAY) {
  const d = new Date(t);
  const h = lib(new Date(d.getUTCFullYear(), d.getUTCMonth(), d.getUTCDate()));
  const entry = years.get(h.hy) ?? { start: null, lengths: new Array(12).fill(0) };
  if (h.hm === 1 && h.hd === 1) entry.start = t / DAY;
  entry.lengths[h.hm - 1] = Math.max(entry.lengths[h.hm - 1], h.hd);
  years.set(h.hy, entry);
}

const rows = [];
for (const [hy, { start, lengths }] of [...years.entries()].sort((a, b) => a[0] - b[0])) {
  if (start === null || lengths.some((l) => l !== 29 && l !== 30)) {
    throw new Error(`Year ${hy} is incomplete: ${JSON.stringify(lengths)}`);
  }
  const mask = lengths.reduce((m, l, i) => (l === 30 ? m | (1 << i) : m), 0);
  rows.push([hy, start, mask]);
}

const body = rows.map(([hy, start, mask]) => `  [${hy}, ${start}, ${mask}],`).join('\n');
writeFileSync(
  new URL('../src/prayer/umalqura-data.ts', import.meta.url),
  `// Generated by scripts/gen-umalqura.mjs. Do not edit by hand.
//
// Umm al-Qura month starts for 1318 to 1500 AH (1900 to 2077). Each row is
// [Hijri year, days since 1970-01-01 of 1 Muharram, month lengths]. In the last number, bit 0 is
// Muharram and a set bit means that month has 30 days; a clear bit means 29.
//
// The calendar data comes from @umalqura/core 0.0.7 (MIT licence, Copyright (c) 2019 Alaa Masoud,
// https://github.com/umalqura/umalqura), read out day by day and stored here
// so the date does not depend on the phone's time zone. src/prayer/hijri.test.ts checks every
// day against that library.
export const UMALQURA_YEARS: readonly (readonly [year: number, firstDay: number, longMonths: number])[] = [
${body}
];
`,
);
console.log(rows.length, 'years');
